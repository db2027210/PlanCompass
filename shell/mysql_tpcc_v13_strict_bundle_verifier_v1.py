#!/usr/bin/env python3
"""Fail-closed verifier for the TPC-C v13 dedicated-daemon successor."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


EXPECTED_SCHEMA = "mysql_tpcc_v13_dedicated_daemon_successor_bundle_v2"


class VerificationError(RuntimeError):
    pass


def canonical(value: object) -> bytes:
    return (
        json.dumps(
            value,
            ensure_ascii=True,
            indent=2,
            sort_keys=True,
            allow_nan=False,
        )
        + "\n"
    ).encode("utf-8")


def digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            value.update(block)
    return value.hexdigest()


def verify(bundle: Path) -> dict[str, object]:
    bundle = bundle.resolve(strict=True)
    manifest_path = bundle / "bundle_manifest.json"
    sidecar_path = bundle / "bundle_manifest.json.sha256"
    if manifest_path.is_symlink() or not manifest_path.is_file():
        raise VerificationError("bundle manifest is absent or a symlink")
    if sidecar_path.is_symlink() or not sidecar_path.is_file():
        raise VerificationError("bundle manifest sidecar is absent or a symlink")

    raw = manifest_path.read_bytes()
    manifest = json.loads(raw)
    manifest_sha256 = hashlib.sha256(raw).hexdigest()
    unsigned = dict(manifest)
    unsigned.pop("bundle_id", None)
    bundle_id = hashlib.sha256(canonical(unsigned)).hexdigest()
    if (
        raw != canonical(manifest)
        or manifest.get("bundle_id") != bundle_id
        or bundle.name != bundle_id
        or manifest.get("schema_version") != EXPECTED_SCHEMA
        or manifest.get("formal_scope") != "mysql_only"
        or manifest.get("cross_engine_comparison_prohibited") is not True
        or manifest.get("formal_launch_authorized") is not False
        or manifest.get("accepted_round_authorized") is not False
    ):
        raise VerificationError("manifest identity, scope, or authority differs")
    expected_sidecar = (
        manifest_sha256 + "  bundle_manifest.json\n"
    ).encode("ascii")
    if sidecar_path.read_bytes() != expected_sidecar:
        raise VerificationError("bundle manifest sidecar differs")

    declared = manifest.get("files")
    if not isinstance(declared, dict) or not declared:
        raise VerificationError("manifest file closure is absent")
    expected_paths = set(declared) | {
        "bundle_manifest.json",
        "bundle_manifest.json.sha256",
    }
    actual_paths: set[str] = set()
    for candidate in bundle.rglob("*"):
        relative = candidate.relative_to(bundle).as_posix()
        if candidate.is_symlink():
            raise VerificationError("symlink in sealed tree: " + relative)
        if candidate.is_file():
            actual_paths.add(relative)
        elif not candidate.is_dir():
            raise VerificationError("non-regular entry in sealed tree: " + relative)
    if actual_paths != expected_paths:
        missing = sorted(expected_paths - actual_paths)
        extra = sorted(actual_paths - expected_paths)
        raise VerificationError(
            "strict file closure differs; missing=%r extra=%r" % (missing, extra)
        )
    for relative, expected_digest in declared.items():
        candidate = bundle / relative
        if digest(candidate) != expected_digest:
            raise VerificationError("file digest differs: " + relative)

    forbidden = [
        relative
        for relative in actual_paths
        if "__pycache__" in Path(relative).parts
        or relative.endswith((".pyc", ".pyo"))
    ]
    if forbidden:
        raise VerificationError("generated bytecode in sealed tree: " + forbidden[0])
    return {
        "status": "PASS_STRICT_CLOSED_TPCC_V13_BUNDLE",
        "bundle": str(bundle),
        "bundle_id": bundle_id,
        "bundle_manifest_sha256": manifest_sha256,
        "declared_files": len(declared),
        "extra_files": 0,
        "generated_bytecode_files": 0,
        "formal_launch_authorized": False,
        "accepted_round_authorized": False,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bundle", type=Path, required=True)
    args = parser.parse_args()
    print(json.dumps(verify(args.bundle), sort_keys=True))


if __name__ == "__main__":
    try:
        main()
    except VerificationError as exc:
        raise SystemExit("NOT_READY: %s" % exc)
