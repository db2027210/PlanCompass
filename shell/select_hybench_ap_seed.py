#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
import json
import math
import random
import re
import shutil
import statistics
import subprocess
import sys
import time
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple


QPS_RE = re.compile(r"\bResult:\d+\s+-\s+QPS is\s+([0-9.]+|Infinity|NaN)")
CURRENT_QPS_RE = re.compile(r"\bCurrent\s+\d+/\d+\s+time AP QPS is\s+([0-9.]+|Infinity|NaN)")
RUN_LIST_RE = re.compile(r"Run List in current round\s+\d+\s+:\s+(.+)$")
AP_QUERY_RE = re.compile(
    r"AP Query\s+(\d+)\s+:\s+max rt :\s+([0-9.]+|Infinity|NaN)"
    r"\s+\|\s+min rt :\s+([0-9.]+|Infinity|NaN)"
    r"\s+\|\s+avg rt :\s+([0-9.]+|Infinity|NaN)"
    r"\s+\|\s+90% rt :\s+([0-9.]+|Infinity|NaN)"
    r"\s+\|\s+95% rt :\s+([0-9.]+|Infinity|NaN)"
    r"\s+\|\s+99% rt :\s+([0-9.]+|Infinity|NaN)"
)


def parse_float(value: str) -> Optional[float]:
    if value == "Infinity" or value == "NaN":
        return None
    try:
        parsed = float(value)
    except ValueError:
        return None
    if math.isfinite(parsed):
        return parsed
    return None


def set_prop_lines(text: str, updates: Dict[str, str]) -> str:
    seen = set()
    output: List[str] = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            key = stripped.split("=", 1)[0].strip()
            if key in updates:
                output.append(f"{key}={updates[key]}")
                seen.add(key)
                continue
        output.append(line)

    missing = [key for key in updates if key not in seen]
    if missing:
        output.append("")
        output.append("# Generated by select_hybench_ap_seed.py")
        for key in missing:
            output.append(f"{key}={updates[key]}")
    return "\n".join(output) + "\n"


def parse_log(log_text: str) -> Dict[str, object]:
    final_qps: Optional[float] = None
    current_qps_values: List[float] = []
    first_run_list: Optional[str] = None
    ap_rows: List[Dict[str, float]] = []

    for line in log_text.splitlines():
        qps_match = QPS_RE.search(line)
        if qps_match:
            final_qps = parse_float(qps_match.group(1))

        current_match = CURRENT_QPS_RE.search(line)
        if current_match:
            current_qps = parse_float(current_match.group(1))
            if current_qps is not None:
                current_qps_values.append(current_qps)

        if first_run_list is None:
            run_list_match = RUN_LIST_RE.search(line)
            if run_list_match:
                first_run_list = " ".join(run_list_match.group(1).split())

        ap_match = AP_QUERY_RE.search(line)
        if ap_match:
            values = [parse_float(ap_match.group(i)) for i in range(2, 8)]
            if all(v is not None for v in values):
                max_rt, min_rt, avg_rt, p90_rt, p95_rt, p99_rt = values
                ap_rows.append(
                    {
                        "query": float(ap_match.group(1)),
                        "max_ms": float(max_rt),
                        "min_ms": float(min_rt),
                        "avg_ms": float(avg_rt),
                        "p90_ms": float(p90_rt),
                        "p95_ms": float(p95_rt),
                        "p99_ms": float(p99_rt),
                    }
                )

    avg_ap_avg = statistics.mean(row["avg_ms"] for row in ap_rows) if ap_rows else None
    avg_ap_p95 = statistics.mean(row["p95_ms"] for row in ap_rows) if ap_rows else None
    max_ap_p99 = max((row["p99_ms"] for row in ap_rows), default=None)
    current_qps_mean = statistics.mean(current_qps_values) if current_qps_values else None
    current_qps_cv = None
    if current_qps_values and len(current_qps_values) > 1 and current_qps_mean and current_qps_mean > 0:
        current_qps_cv = statistics.stdev(current_qps_values) / current_qps_mean

    return {
        "final_qps": final_qps,
        "current_qps_mean": current_qps_mean,
        "current_qps_cv": current_qps_cv,
        "avg_ap_avg_ms": avg_ap_avg,
        "avg_ap_p95_ms": avg_ap_p95,
        "max_ap_p99_ms": max_ap_p99,
        "first_run_list": first_run_list,
        "ap_query_count": len(ap_rows),
    }


def balanced_score(row: Dict[str, object]) -> Optional[float]:
    qps = row.get("final_qps")
    if not isinstance(qps, float):
        return None
    avg_p95 = row.get("avg_ap_p95_ms")
    qps_cv = row.get("current_qps_cv")
    latency_penalty = (avg_p95 / 10000.0) if isinstance(avg_p95, float) else 0.0
    stability_penalty = qps_cv if isinstance(qps_cv, float) else 0.0
    return qps / (1.0 + latency_penalty + stability_penalty)


def representative_score(row: Dict[str, object], med_qps: float, med_p95: Optional[float]) -> Optional[float]:
    qps = row.get("final_qps")
    if not isinstance(qps, float) or med_qps <= 0:
        return None
    qps_dist = abs(qps - med_qps) / med_qps
    p95_dist = 0.0
    avg_p95 = row.get("avg_ap_p95_ms")
    if isinstance(avg_p95, float) and med_p95 and med_p95 > 0:
        p95_dist = abs(avg_p95 - med_p95) / med_p95
    return -(qps_dist + p95_dist)


def run_command(cmd: Sequence[str], cwd: Path, log_path: Path) -> int:
    with log_path.open("w", encoding="utf-8") as log_file:
        proc = subprocess.run(
            list(cmd),
            cwd=str(cwd),
            stdout=log_file,
            stderr=subprocess.STDOUT,
            text=True,
            check=False,
        )
    return proc.returncode


def run_before_cmd(cmd: str, cwd: Path) -> None:
    if not cmd:
        return
    subprocess.run(cmd, cwd=str(cwd), shell=True, check=False)


def choose_best(rows: List[Dict[str, object]], key: str) -> Optional[Dict[str, object]]:
    valid = [row for row in rows if isinstance(row.get(key), float)]
    if not valid:
        return None
    return max(valid, key=lambda row: float(row[key]))


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Run HyBench AP with multiple deterministic random_seed values and rank the seeds."
    )
    parser.add_argument("--hybench-dir", default="/home/anonymous/HyBench-2024-master")
    parser.add_argument("--props", default="conf/pg.props")
    parser.add_argument("--stmt", default="conf/stmt_postgres.toml")
    parser.add_argument("--output-dir", default="")
    parser.add_argument("--seeds", nargs="*", type=int, default=None)
    parser.add_argument("--random-count", type=int, default=0, help="Generate this many random seed candidates.")
    parser.add_argument("--seed-min", type=int, default=1, help="Minimum generated seed value, inclusive.")
    parser.add_argument("--seed-max", type=int, default=2_147_483_647, help="Maximum generated seed value, inclusive.")
    parser.add_argument(
        "--seed-random-state",
        type=int,
        default=20260509,
        help="Local RNG seed used to generate random seed candidates.",
    )
    parser.add_argument("--apclient", type=int, default=8)
    parser.add_argument("--run-mins", type=int, default=3)
    parser.add_argument("--fixed-ap-query-order", action=argparse.BooleanOptionalAction, default=True)
    parser.add_argument("--ap-query-order", default="")
    parser.add_argument("--before-cmd", default="", help="Optional shell command to run before each seed, e.g. drop cache.")
    parser.add_argument("--keep-temp-props", action="store_true")
    args = parser.parse_args(argv)

    hybench_dir = Path(args.hybench_dir).resolve()
    props_path = (hybench_dir / args.props).resolve()
    stmt_path = args.stmt
    if not props_path.exists():
        raise FileNotFoundError(f"props file not found: {props_path}")

    if args.output_dir:
        output_dir = Path(args.output_dir).resolve()
    else:
        output_dir = Path.cwd() / "result" / f"hybench_seed_selection_{time.strftime('%Y%m%d_%H%M%S')}"
    output_dir.mkdir(parents=True, exist_ok=True)

    explicit_seeds = list(args.seeds or [])
    generated_seeds: List[int] = []
    if args.random_count > 0:
        if args.seed_max < args.seed_min:
            raise ValueError("--seed-max must be >= --seed-min")
        population_size = args.seed_max - args.seed_min + 1
        if args.random_count > population_size:
            raise ValueError("--random-count is larger than the configured seed range")
        rng = random.Random(args.seed_random_state)
        generated = set()
        while len(generated) < args.random_count:
            generated.add(rng.randint(args.seed_min, args.seed_max))
        generated_seeds = sorted(generated)

    seeds = explicit_seeds + [seed for seed in generated_seeds if seed not in explicit_seeds]
    if not seeds:
        seeds = [20260509, 20260510, 20260511, 20260512, 20260513]

    base_props = props_path.read_text(encoding="utf-8")
    rows: List[Dict[str, object]] = []

    print(f"Seed candidates ({len(seeds)}): {' '.join(str(seed) for seed in seeds)}", flush=True)

    for seed in seeds:
        temp_props = hybench_dir / "conf" / f"pg.props.seed_{seed}.tmp"
        updates = {
            "random_seed": str(seed),
            "fixed_ap_query_order": str(args.fixed_ap_query_order).lower(),
            "apclient": str(args.apclient),
            "apRunMins": str(args.run_mins),
        }
        if args.ap_query_order:
            updates["ap_query_order"] = args.ap_query_order
        temp_props.write_text(set_prop_lines(base_props, updates), encoding="utf-8")

        log_path = output_dir / f"seed_{seed}.log"
        run_before_cmd(args.before_cmd, hybench_dir)
        cmd = ["bash", "hybench", "-t", "runap", "-c", str(temp_props.relative_to(hybench_dir)), "-f", stmt_path]
        print(f"[seed {seed}] running: {' '.join(cmd)}", flush=True)
        returncode = run_command(cmd, hybench_dir, log_path)
        log_text = log_path.read_text(encoding="utf-8", errors="replace")
        parsed = parse_log(log_text)
        row: Dict[str, object] = {
            "seed": seed,
            "returncode": returncode,
            "log_path": str(log_path),
            **parsed,
        }
        row["balanced_score"] = balanced_score(row)
        rows.append(row)
        print(
            f"[seed {seed}] rc={returncode} qps={row.get('final_qps')} "
            f"avg_p95={row.get('avg_ap_p95_ms')} score={row.get('balanced_score')}",
            flush=True,
        )
        if not args.keep_temp_props:
            temp_props.unlink(missing_ok=True)

    qps_values = [float(row["final_qps"]) for row in rows if isinstance(row.get("final_qps"), float)]
    p95_values = [float(row["avg_ap_p95_ms"]) for row in rows if isinstance(row.get("avg_ap_p95_ms"), float)]
    med_qps = statistics.median(qps_values) if qps_values else 0.0
    med_p95 = statistics.median(p95_values) if p95_values else None
    for row in rows:
        row["representative_score"] = representative_score(row, med_qps, med_p95)

    csv_path = output_dir / "seed_summary.csv"
    fieldnames = [
        "seed",
        "returncode",
        "final_qps",
        "current_qps_mean",
        "current_qps_cv",
        "avg_ap_avg_ms",
        "avg_ap_p95_ms",
        "max_ap_p99_ms",
        "balanced_score",
        "representative_score",
        "ap_query_count",
        "first_run_list",
        "log_path",
    ]
    with csv_path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row.get(key, "") for key in fieldnames})

    best_qps = choose_best(rows, "final_qps")
    best_balanced = choose_best(rows, "balanced_score")
    best_representative = choose_best(rows, "representative_score")
    summary = {
        "output_dir": str(output_dir),
        "csv_path": str(csv_path),
        "median_qps": med_qps,
        "median_avg_ap_p95_ms": med_p95,
        "best_by_qps": best_qps,
        "best_by_balanced_score": best_balanced,
        "best_representative_seed": best_representative,
        "rows": rows,
    }
    json_path = output_dir / "seed_summary.json"
    json_path.write_text(json.dumps(summary, ensure_ascii=False, indent=2), encoding="utf-8")

    print("\nSummary files:", flush=True)
    print(f"  {csv_path}", flush=True)
    print(f"  {json_path}", flush=True)
    if best_balanced:
        print(
            f"\nRecommended balanced seed: {best_balanced['seed']} "
            f"(qps={best_balanced.get('final_qps')}, avg_p95={best_balanced.get('avg_ap_p95_ms')})",
            flush=True,
        )
    if best_representative:
        print(
            f"Representative seed: {best_representative['seed']} "
            f"(qps={best_representative.get('final_qps')}, avg_p95={best_representative.get('avg_ap_p95_ms')})",
            flush=True,
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
